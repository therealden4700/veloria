// Заставка титульного экрана — единственная картинка в проекте.
//
// Всё остальное в игре рисуется кодом при запуске, и это осознанно: ни одного
// внешнего файла, ни одной зависимости от художника. Заставка — исключение:
// нарисовать такой пейзаж процедурно нельзя, а титульный экран — единственное
// место, где картинка стоит на месте и её не нужно сочетать с генерацией.
//
// Файл лежит ровно в 480×270 — во внутреннем разрешении игры. Поэтому он
// рисуется один к одному, без сглаживания, и увеличивается вместе со всем
// кадром той же лестницей пикселей. Хранить его крупнее смысла нет: канвас всё
// равно 480 пикселей шириной, а так заставка весит 265 КБ вместо двух с
// половиной мегабайт.

const SRC = './assets/title.png';

let img = null;
let state = 'idle';   // idle → loading → ready | failed

/** Заставка, если она уже загружена. Иначе null — рисуется запасной фон. */
export function titleArt() {
  if (state === 'idle') load();
  return state === 'ready' ? img : null;
}

/**
 * Начать загрузку. Ошибка не роняет игру: титульный экран умеет обходиться
 * своим фоном, и потеря файла не должна оставлять игрока перед чёрным экраном.
 */
export function load() {
  if (state !== 'idle') return Promise.resolve(state === 'ready');
  state = 'loading';
  img = new Image();
  return new Promise((resolve) => {
    img.onload = () => { state = 'ready'; resolve(true); };
    img.onerror = () => { state = 'failed'; img = null; resolve(false); };
    img.src = SRC;
  });
}
