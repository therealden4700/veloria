// Ветер: одно поле на весь мир вместо случайной фазы у каждого дерева.
//
// Покачивание крон было и раньше, и амплитуда у него честная — замер показал
// 106 качающихся крон в кадре со сдвигом верхушки около 7,6 экранных пикселя.
// Беда была не в размахе, а в согласованности: каждое дерево качалось само по
// себе, с собственной случайной фазой и периодом от 2,7 до 12,3 секунды.
// Соседние кроны шли в разные стороны, и вместе это читалось не ветром, а желе.
//
// Настоящий ветер идёт волной и порывами. Здесь одно поле на весь мир: волна
// бежит поперёк карты в одну сторону, поверх неё медленная огибающая порывов —
// ветер то стихает, то налетает, — и лишь пятая часть размаха остаётся на
// личную фазу объекта, чтобы строй не выглядел машинным.
//
// Размах поля тот же, что был у одиночного синуса (примерно ±1), поэтому
// амплитуду покачивания это не меняет: только делает её общей.

const DIRX = 0.94, DIRY = 0.34;   // куда дует — наискось, а не строго вбок
const WAVE = 1 / 190;             // длина порыва в пикселях мира: ~2,5 гребня на экран
const SPEED = 1.9;                // рад/с: гребень проходит свою длину за 3,3 с
const GUST = 0.21;                // огибающая порывов — заметно медленнее самой волны
const OWN = 0.22;                 // доля личной фазы: без неё строй машинный

/**
 * Отклонение ветра в точке мира, примерно в пределах ±1.
 *
 * `phase` и `speed` — личные у объекта: они остаются от прежнего покачивания и
 * дают той самой пятой части разнобой.
 */
export function windAt(x, y, t, phase = 0, speed = 1) {
  const wave = Math.sin((x * DIRX + y * DIRY) * WAVE - t * SPEED);
  // Дно огибающей — не ноль: при 0,10 замер показал затишье на несколько
  // секунд, когда лес почти замирает, и это читается не как безветрие, а как
  // сломавшаяся анимация. 0,24 оставляет заметное дыхание между порывами.
  const gust = 0.62 + 0.38 * Math.sin(t * GUST + (x + y) * 0.0006);
  const own = Math.sin(t * speed + phase);
  return (wave * (1 - OWN) + own * OWN) * gust;
}
