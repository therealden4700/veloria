// Бездна — то, во что превращаются катакомбы за 25-м этажом.
//
// Замер показал, в чём была настоящая проблема глубины: она не ломалась, она
// провисала. На сотом этаже герой убивал моба за 12,8 удара, а сам умирал за
// 18,5 — бои растягивались, но опасность не росла. Классическая инфляция чисел.
//
// Поэтому Порча бьёт не по здоровью мобов (это дало бы ещё более длинные бои),
// а по запасу прочности героя: сжимает шкалу жизни и пробивает потолок брони.
// Здоровье мобов, наоборот, растёт с глубиной медленнее прежнего.

import { clamp } from '../core/util.js';

/** С этого этажа катакомбы становятся Бездной. */
export const ABYSS_START = 26;
/** Дальше порча не растёт — иначе кривая уходит в отвес. */
export const CORRUPTION_MAX = 40;

/** Уровень порчи этажа. 0 — обычные катакомбы. */
export function corruptionOf(zone) {
  if (!zone || zone.kind !== 'dungeon' || !zone.floor) return 0;
  return clamp(zone.floor - (ABYSS_START - 1), 0, CORRUPTION_MAX);
}

/**
 * Что порча делает. Рычага два: шкала жизни героя и урон врагов.
 *
 * Третьим напрашивалась броня, но замер показал, что снижение урона у героя и
 * так держится около 50% и в потолок 82% не упирается — пробивать было нечего.
 * Убран как рычаг, который ничего не делает, но усложняет модель.
 *
 * Коэффициенты подобраны по симуляции: ударов до смерти героя падает
 * 18 → 11 → 7 → 3 с 26-го по 65-й этаж и дальше выполаживается, а не уходит
 * в ноль — иначе глубина упиралась бы в стену «убивают с одного удара».
 */
export function corruptionEffects(c) {
  return {
    hpMul:    Math.max(0.50, 1 - c * 0.013),   // Бездна съедает шкалу жизни
    enemyDmg: 1 + c * 0.025,
    enemySpd: 1 + Math.min(0.40, c * 0.012),
    lootMul:  1 + c * 0.09,
    xpMul:    1 + c * 0.07,
    // на глубине перестаёт падать хлам: порог сдвигает нижние ступени редкости
    rarityFloor: Math.min(3, Math.floor(c / 9)),
  };
}

/**
 * Уровень мобов на этаже. За порогом Бездны рост замедляется втрое: дальше
 * сложность держит порча, а не растущая гора здоровья.
 */
export function dungeonLevel(floor) {
  if (floor < ABYSS_START) return Math.max(1, Math.round(2 + floor * 1.75));
  const base = 2 + (ABYSS_START - 1) * 1.75;
  return Math.round(base + (floor - ABYSS_START + 1) * 0.45);
}

/**
 * Босс глубины. До Бездны это всегда Лич — так задумано сюжетом; дальше
 * стражи чередуются, иначе двадцать шесть боссовых этажей подряд были бы
 * одним и тем же боем.
 */
export const ABYSS_BOSSES = ['voidMaw', 'hollowKing', 'emberWidow', 'rootWarden', 'lich'];

export function dungeonBoss(floor) {
  if (floor < ABYSS_START) return 'lich';
  const i = Math.floor((floor - ABYSS_START) / 5) % ABYSS_BOSSES.length;
  return ABYSS_BOSSES[i];
}

/** Короткое описание порчи для интерфейса. */
export function corruptionLines(c) {
  const e = corruptionEffects(c);
  // третье поле — награда это или цена: цвет не должен зависеть от разбора строки
  return [
    ['Здоровье героя', `−${Math.round((1 - e.hpMul) * 100)}%`, false],
    ['Урон врагов', `+${Math.round((e.enemyDmg - 1) * 100)}%`, false],
    ['Скорость врагов', `+${Math.round((e.enemySpd - 1) * 100)}%`, false],
    ['Добыча и опыт', `+${Math.round((e.lootMul - 1) * 100)}% / +${Math.round((e.xpMul - 1) * 100)}%`, true],
  ];
}

/** Название ступени — чтобы глубина читалась не только числом. */
export function corruptionName(c) {
  if (c <= 0) return null;
  if (c < 6) return 'Порча · дыхание';
  if (c < 13) return 'Порча · хватка';
  if (c < 22) return 'Порча · жажда';
  if (c < 33) return 'Порча · утроба';
  return 'Порча · дно';
}
