const hasGear = (p, fn) => {
  for (const s of ['weapon', 'armor', 'helm', 'ring', 'amulet']) {
    const it = p.equipment[s];
    if (it && fn(it)) return true;
  }
  return false;
};
const inBag = (p, fn) => p.inventory.some(fn);

