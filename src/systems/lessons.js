/**
 * Первый неоткрытый урок, условие которого выполнено. Возвращает null, если
 * показывать нечего. Порядок в таблице — приоритет: базовые системы раньше.
 */
/**
 * Тишина между обучающими карточками, секунды.
 *
 * Отсчитывается от того мгновения, когда карточка ушла с экрана. Число не с
 * потолка: карточка живёт 9,5 с, и с этой паузой подсказки приходят не чаще
 * чем раз в двадцать секунд. Замер входа показывал 10 с — карточки шли встык.
 */
export const LESSON_GAP = 10;

export function nextLesson(game, seen) {
  for (const l of LESSONS) {
    if (seen[l.key]) continue;
    let ok = false;
    try { ok = l.when(game); } catch { ok = false; }
    if (ok) return l;
  }
  return null;
}
