// Мерить тут есть что помимо самого умолчания. Часть надписей живёт в разметке
// и в DOM, а не на канвасе: заставка появляется раньше, чем выполнится первая
// строка кода, а подсказку про поворот экрана надо показать до того, как игра
// вообще загрузится. Эти места мимо словаря, и проглядеть их легко — что и
// случилось: язык восстанавливал конструктор `Game`, а он создаётся уже после
// экрана загрузки, и две первые строки человек видел на чужом языке.
//
// ЧЕГО ЭТОТ СТЕНД НЕ МЕРЯЕТ. Вёрстку: английский длиннее русского, и влезает ли
// он в кнопки — видно только в браузере. И качество перевода.

