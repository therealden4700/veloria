// Язык: английский по умолчанию, русский — выбором, и никаких утечек до кадра.
//
//   node tools/lang-check.js
//
// Ключи словаря русские, и русским же долго был язык по умолчанию — просто
// потому, что так писался код. Игра лежит по открытой ссылке, и человек,
// попавший на неё, скорее прочтёт английский. Русский никуда не делся: он в
// настройках, в двух щелчках, и выбор запоминается.
