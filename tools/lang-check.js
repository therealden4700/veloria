// Язык: английский по умолчанию, русский — выбором, и никаких утечек до кадра.
//
//   node tools/lang-check.js
//
// Ключи словаря русские, и русским же долго был язык по умолчанию — просто
// потому, что так писался код. Игра лежит по открытой ссылке, и человек,
// попавший на неё, скорее прочтёт английский. Русский никуда не делся: он в
// настройках, в двух щелчках, и выбор запоминается.
//
// Мерить тут есть что помимо самого умолчания. Часть надписей живёт в разметке
// и в DOM, а не на канвасе: заставка появляется раньше, чем выполнится первая
// строка кода, а подсказку про поворот экрана надо показать до того, как игра
// вообще загрузится. Эти места мимо словаря, и проглядеть их легко — что и
// случилось: язык восстанавливал конструктор `Game`, а он создаётся уже после
// экрана загрузки, и две первые строки человек видел на чужом языке.
//
// ЧЕГО ЭТОТ СТЕНД НЕ МЕРЯЕТ. Вёрстку: английский длиннее русского, и влезает ли
// он в кнопки — видно только в браузере. И качество перевода.

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const файл = (p) => readFileSync(resolve(ROOT, p), 'utf8');

const problems = [];
const note = (s) => problems.push(s);
const log = (s) => console.log(s);
let сделано = 0;
const проверить = (имя, годно, замер, причина) => {
  сделано++;
  log(`  ${годно ? '✓' : '✗'} ${имя}${замер ? '  — ' + замер : ''}${!годно && причина ? '  (' + причина + ')' : ''}`);
  if (!годно) note(`${имя}: ${причина || замер || 'не сошлось'}`);
};

const { getLang, setLang, initLang, t, LANGS } = await import('../src/core/i18n.js');

// ══════════════════════════════ умолчание и память

log('── умолчание и память');

проверить('без сохранённого выбора — английский', getLang() === 'en', getLang(),
  'первое, что видит человек по ссылке, на языке, которого он может не знать');
проверить('оба языка на месте', LANGS.length === 2 && LANGS.some((L) => L.id === 'ru') && LANGS.some((L) => L.id === 'en'),
  LANGS.map((L) => L.id).join(', '), 'переключать не на что');

проверить('сохранённый выбор сильнее умолчания', initLang('ru') === 'ru', initLang('ru'),
  'выбранный однажды язык не переживает перезагрузку');
проверить('мусор вместо языка не принимается', initLang('эльфийский') === 'ru', initLang('эльфийский'),
  'испорченные настройки меняют язык на неизвестный');
проверить('пустые настройки не сбивают выбор', initLang(undefined) === 'ru', initLang(undefined),
  'отсутствие записи трактуется как смена языка');

setLang('en');
проверить('переключение работает в обе стороны', getLang() === 'en', getLang(), 'обратно не переключить');

// ══════════════════════════════ надписи вне канваса

log('');
log('── надписи, которые рисует не игра');

// Заставка и подсказка поворота пишутся в DOM. Строки достаём из самих файлов,
// а не переписываем сюда: список в двух местах — это будущее расхождение.
const main = файл('src/main.js');
const шаги = [...main.matchAll(/\['([^']+)',\s*\(\)\s*=>/g)].map((m) => m[1]);
const прямые = [...main.matchAll(/t\('([^']+)'\)/g)].map((m) => m[1]);
const изРазметки = [...файл('index.html').matchAll(/>([^<>]*[А-Яа-яЁё][^<>]*)</g)]
  .map((m) => m[1].trim())
  .filter((s) => s && !s.startsWith('<!--'));

проверить('шаги загрузки берутся из кода', шаги.length > 0, `${шаги.length} шага`, 'нечего проверять');
for (const s of [...шаги, ...прямые]) {
  проверить(`переведено: «${s}»`, t(s) !== s, t(s),
    'надпись уйдёт в DOM по-русски при английском языке');
}

проверить('в видимой разметке не осталось русского', изРазметки.length === 0,
  изРазметки.length ? изРазметки.join(' | ').slice(0, 90) : 'чисто',
  'первый кадр рисует браузер, и он покажет ровно то, что записано в файле');

const html = файл('index.html');
проверить('страница объявлена английской', /<html lang="en">/.test(html),
  (html.match(/<html lang="(\w+)">/) || [])[1] || 'нет',
  'чтение с экрана и перевод браузера будут считать страницу русской');

// ══════════════════════════════ экран входа

log('');
log('── экран входа');

// Тот самый первый экран: кошелёк, гость и две строки под кнопками.
const вход = ['Установить Phantom', 'Играть гостем', 'Продолжить',
  'Кошелька Phantom не видно — можно играть гостем',
  'Игра никогда не спросит seed-фразу и не попросит подтвердить перевод'];
for (const s of вход) {
  проверить(`переведено: «${s.slice(0, 34)}${s.length > 34 ? '…' : ''}»`, t(s) !== s, '',
    'на экране входа останется русская строка');
}

// Настройки должны называть языки так, чтобы их узнал носитель каждого.
проверить('русский назван по-русски', LANGS.find((L) => L.id === 'ru').name === 'Русский', '',
  'носитель не найдёт свой язык в списке');
проверить('английский назван по-английски', LANGS.find((L) => L.id === 'en').name === 'English', '', '');

console.log('');
console.log(`проверок: ${сделано}`);
if (problems.length) {
  console.log(`найдено: ${problems.length}`);
  for (const p of problems) console.log('  ' + p);
  process.exit(1);
}
console.log('ПРОБЛЕМ НЕ НАЙДЕНО');
process.exit(0);
