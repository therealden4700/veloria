// Всё ниже найдено проверкой готовности к релизу. Строки берём из самих
// файлов — списка в стенде быть не должно, он разойдётся с игрой на первой же
// правке.

/** Тело метода класса: от объявления до следующего объявления того же уровня. */
const тело = (текст, имя) => {
  const н = текст.indexOf(`  ${имя}(`);
  if (н < 0) return '';
  const дальше = текст.slice(н + имя.length + 4).search(/\n {2}[a-zA-Zа-яА-Я_]+\(/);
  return дальше < 0 ? текст.slice(н) : текст.slice(н, н + имя.length + 4 + дальше);
};
/**
 * Русские строковые литералы из куска кода.
 *
 * Комментарии снимаем ДО разбора. В этом проекте они длинные и по-русски, а
 * апострофы в них есть: без очистки кавычка из одного места ловилась в пару с
 * кавычкой из другого, и «литералом» становился кусок кода на двадцать строк.
 */
const литералы = (текст) => {
  const чисто = текст.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|\s)\/\/[^\n]*/g, '$1');
  return [...new Set(
    [...чисто.matchAll(/'([^'\n\\]*[А-Яа-яЁё][^'\n\\]*)'/g)].map((m) => m[1])
      .filter((x) => x.trim().length > 1),
  )];
};
/** Короткий список для замера: длинный отчёт нечитаем. */
const коротко = (сп, n = 5) => сп.slice(0, n).map((x) => x.slice(0, 26)).join(' | ') + (сп.length > n ? ` … +${сп.length - n}` : '');
const непереведено = (список) => список.filter((x) => t(x) === x);

