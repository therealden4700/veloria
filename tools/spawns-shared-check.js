// Что рождается по ходу игры — рождает комната, и оно одно на всех.
//
//   node tools/spawns-shared-check.js [биом]
//
// До сих пор и стража, и засадные отряды рождал клиент. Для стража это значило
// «у каждого свой, сервер о нём не знает» — а с него падает лучшее в биоме. Для
// засады хуже: комната о таком отряде не знает, в снимке его нет, а клиент
// хоронит всё, чего в снимке нет, — с полной добычей и опытом. Подошёл к лагерю
// и получил награду за отряд, которого никто не видел.
//
// Здесь проверяется обратное: рождает комната — по порогу входа, — оно одно на
// всех, здоровье общее, и лагерь взводится заново, а не достаётся первому.
//
// Стенд гоняет **саму комнату**, а не разговаривает с сервером по сети. Причина
// прямая: бот ходить не умеет — пути в игре нет ни у кого, — а арена стража
// стоит далеко от входа. Стенд, который туда не дошёл, сказал бы «босс не
// появился», и это было бы про обходы деревьев, а не про игру. Сеть при этом
// уже проверена другими стендами.
//
// ЧЕГО ЭТОТ СТЕНД НЕ МЕРЯЕТ. Он не проверяет зрелище: баннер, музыку, тряску —
// это клиентская половина, и её видно только в браузере.

import { World, prepareArt } from '../server/world.js';

const problems = [];
const note = (s) => problems.push(s);
const log = (s) => console.log(s);

prepareArt();

const БИОМ = process.argv[2] || 'forest';
const w = new World({ kind: 'biome', id: БИОМ, seed: 20260805 });
const z = w.zone;
if (!z.boss) { console.log(`в биоме ${БИОМ} нет стража — мерить нечего`); process.exit(0); }

const радиус = z.bossArena ? z.bossArena.r : 130;
log(`${z.name}: населения ${w.enemies.length}, страж ${z.boss.key} ур. ${z.boss.level} в (${Math.round(z.boss.x)}, ${Math.round(z.boss.y)}), арена ${радиус} px`);

const шаг = (сек) => { for (let t = 0; t < сек; t += 1 / 20) w.step(1 / 20); };
const стражи = () => w.enemies.filter((e) => e.boss);
const снимок = () => w.snapshot();
const вСнимке = (nid) => (снимок().enemies || []).find((e) => e.i === nid);

// ── двое в комнате: один пойдёт в арену, второй останется у входа
const A = w.addPlayer({ pid: 1, name: 'Первый', look: {}, character: null });
const Б = w.addPlayer({ pid: 2, name: 'Второй', look: {}, character: null });
for (const p of [A, Б]) { p.level = 40; p.hp = p.maxHp; }
const вход = { x: A.x, y: A.y };
log(`двое вошли в (${Math.round(вход.x)}, ${Math.round(вход.y)}), до арены ${Math.round(Math.hypot(z.boss.x - вход.x, z.boss.y - вход.y))} px`);

// ── пока в арену не вошли, стража быть не должно
шаг(3);
if (стражи().length) note('страж появился, хотя в арену никто не входил — порог не работает');
else log('в арену не входили — стража нет, правильно');

// ── первый входит в арену
A.x = z.boss.x + радиус * 0.5; A.y = z.boss.y;
шаг(1);
const б1 = стражи();
if (б1.length !== 1) {
  note(`после входа в арену стражей ${б1.length}, а надо ровно один`);
} else {
  const b = б1[0];
  log(`вошли в арену: поднялся ${b.key} ур. ${b.level}, ${Math.round(b.hp)} hp, номер #${b.nid}`);
  if (b.nid === undefined || b.nid === null) note('у стража нет номера — клиент не сможет его опознать в снимке');
  if (!вСнимке(b.nid)) note('страж не попал в снимок — клиент его не увидит');
}

// ── второй, стоя далеко, видит того же самого
const b = стражи()[0];
if (b) {
  const вид = вСнимке(b.nid);
  log(`второй у входа (${Math.round(Math.hypot(Б.x - z.boss.x, Б.y - z.boss.y))} px до арены) видит в снимке: ${вид ? вид.k + ' ' + вид.hp + '/' + вид.mx : 'ничего'}`);
  if (!вид) note('второй игрок не видит стража — снимок один на комнату, он обязан быть в нём');

  // ── здоровье общее: бьёт первый, видят оба
  const было = вид ? вид.hp : 0;
  w.damageEnemy(b, 40, { by: A, from: A });
  const стало = вСнимке(b.nid);
  log(`первый ударил: ${было} → ${стало ? стало.hp : 'мёртв'} — второй видит то же число`);
  if (стало && стало.hp >= было) note('удар не снял здоровья — бой стража считает не комната');

  // ── и рана держится
  //
  // Эту проверку добавила ломка: если убрать из `bossTrigger` защиту «уже
  // стоит», страж пересоздаётся каждый такт на том же месте. Стражей
  // по-прежнему один, номер тот же, и стенд был зелёным — а здоровье молча
  // возвращалось к полному, и убить его стало бы нельзя вовсе.
  шаг(2);
  const спустя = вСнимке(b.nid);
  log(`через 2 с рана держится: ${спустя ? спустя.hp + '/' + спустя.mx : 'стража нет'}`);
  if (спустя && спустя.hp >= спустя.mx) note('страж залечился до полного — комната рождает его заново каждый такт');

  // ── и это по-прежнему один страж, а не два
  if (стражи().length !== 1) note(`стражей стало ${стражи().length} — комната рождает второго`);
  A.x = вход.x; A.y = вход.y;      // вышли и вошли снова
  шаг(2);
  A.x = z.boss.x + радиус * 0.5; A.y = z.boss.y;
  шаг(2);
  if (стражи().length !== 1) note(`после повторного входа стражей ${стражи().length} — порог рождает каждый раз`);
  else log('вышли и вошли снова — страж по-прежнему один');
}

// ── убили: возвращается не сразу, и только когда снова придут
const b2 = стражи()[0];
if (b2) {
  const nid = b2.nid, вид = b2.key, полное = Math.round(b2.maxHp);
  w.killEnemy(b2, A);
  log('');
  log(`убит ${вид} #${nid}`);
  if (вСнимке(nid)) note('убитый страж остался в снимке');

  A.x = вход.x; A.y = вход.y;
  шаг(30);
  if (стражи().some((e) => !e.dead)) note('страж вернулся через полминуты — событие превратилось в поголовье');
  else log('через 30 с вдалеке: не вернулся — правильно');

  // ждём его срок (вчетверо больше обычного) и заходим снова
  шаг(200);
  if (стражи().some((e) => !e.dead)) note('страж поднялся сам, без входа в арену — за ним должны прийти');
  else log('срок вышел, но в арену не входили — стража нет, правильно');

  A.x = z.boss.x + радиус * 0.5; A.y = z.boss.y;
  шаг(1);
  const b3 = стражи().find((e) => !e.dead);
  if (!b3) {
    note('страж не вернулся вовсе — в общем мире биом останется без своего лучшего боя');
  } else {
    log(`вернулись в арену: ${b3.key} ${Math.round(b3.hp)}/${Math.round(b3.maxHp)} hp, номер #${b3.nid}`);
    if (b3.nid !== nid) note(`страж вернулся под номером #${b3.nid}, а был #${nid} — номер должен остаться тем же`);
    if (b3.key !== вид) note(`вернулся ${b3.key}, а был ${вид}`);
    if (Math.round(b3.maxHp) !== полное) note(`здоровья ${Math.round(b3.maxHp)}, а было ${полное}`);
    if (стражи().filter((e) => !e.dead).length !== 1) note('живых стражей больше одного');
  }
}

// ═══════════════════════════════════ засадные лагеря

const лагерь = (z.events || []).find((e) => e.kind === 'ambush');
if (!лагерь) {
  log('');
  log(`в биоме ${БИОМ} нет засадных лагерей — эту часть не мерили`);
} else {
  log('');
  log(`лагерь в (${Math.round(лагерь.x)}, ${Math.round(лагерь.y)}), радиус ${Math.round(лагерь.r)} px`);
  const засадные = () => w.enemies.filter((e) => e.pack === 'ambush');

  A.x = вход.x; A.y = вход.y; Б.x = вход.x; Б.y = вход.y;
  шаг(2);
  if (засадные().length) note('отряд поднялся, хотя к лагерю никто не подходил');
  else log('к лагерю не подходили — отряда нет, правильно');

  A.x = лагерь.x; A.y = лагерь.y;
  шаг(1);
  const отряд = засадные();
  log(`подошли: поднялось ${отряд.length}, номера ${отряд.map((e) => '#' + e.nid).join(' ')}`);
  if (!отряд.length) note('лагерь не ожил — засады в общем мире не будет вовсе');
  const без = отряд.filter((e) => e.nid === undefined || !вСнимке(e.nid));
  if (без.length) note(`${без.length} из отряда нет в снимке — клиент их не увидит, а бить их будет комната`);
  const безУровня = отряд.filter((e) => { const v = вСнимке(e.nid); return v && v.lv === undefined; });
  if (безУровня.length) note('в снимке у дописанных нет уровня — клиенту не из чего их собрать');

  // второй раз подходить — не значит поднимать заново
  const мест = w.enemies.length;
  A.x = вход.x; A.y = вход.y; шаг(1);
  A.x = лагерь.x; A.y = лагерь.y; шаг(1);
  if (засадные().length !== отряд.length) note(`после повторного подхода в отряде ${засадные().length}, а было ${отряд.length}`);
  if (w.enemies.length !== мест) note(`список вырос с ${мест} до ${w.enemies.length} — лагерь занимает новые места каждый раз`);
  else log(`подошли снова — отряд тот же, список не вырос (${мест})`);

  // зачистили — лагерь должен взвестись заново, а не достаться первому
  for (const e of засадные()) w.killEnemy(e, A);
  log(`зачищено ${отряд.length}`);
  A.x = вход.x; A.y = вход.y;
  шаг(20);
  if (засадные().some((e) => !e.dead)) note('отряд вернулся через двадцать секунд — лагерь превратился в поголовье');
  шаг(60);
  A.x = лагерь.x; A.y = лагерь.y;
  шаг(1);
  const снова = засадные().filter((e) => !e.dead);
  log(`через минуту с лишним вернулись к лагерю: поднялось ${снова.length}`);
  if (!снова.length) note('лагерь не взвёлся — в общем мире он достанется первому прошедшему навсегда');
  if (w.enemies.length !== мест) note(`список вырос до ${w.enemies.length} — при повторном налёте занимаются новые места`);
}

console.log('');
if (problems.length) {
  console.log(`найдено: ${problems.length}`);
  for (const p of problems) console.log('  ' + p);
  process.exit(1);
}
console.log('ПРОБЛЕМ НЕ НАЙДЕНО');
