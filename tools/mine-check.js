// Что клиент показывает своим, а считает уже комната.
//
//   node tools/mine-check.js [порт]
//
// Две находки проверки готовности к релизу об одном и том же: в общем мире есть
// действия, которые клиент делает у себя на экране, хотя решать их давно должна
// комната. Игрок жмёт — цифры меняются — и через миг возвращаются на место.
//
// Очки развития. Кнопка «+» зовёт `spendStat` — чисто местную операцию, а
// сообщения о трате очков в протоколе нет вовсе. Обучение при этом прямо
// говорит: «за уровень дают 3 очка, вложить — у наставника в Велории».
//
// Зелья. `usePotion` лечит местное здоровье и вычёркивает вещь из местного
// списка, в отличие от покупки, продажи, ковки и заданий — у тех ветка на сеть
// давно есть. Здоровье в общем мире ведёт комната, а рюкзак она же и присылает:
// выпитое зелье возвращается на пояс при первом же обновлении.
//
// ЧЕГО ЭТОТ СТЕНД НЕ МЕРЯЕТ. Одиночную игру: там оба действия местные по
// устройству, и это правильно.

const PORT = Number(process.argv[2] || 3000);
const U = `http://localhost:${PORT}`;
const problems = [];
const note = (s) => problems.push(s);
const log = (s) => console.log(s);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let сделано = 0;
const проверить = (имя, годно, замер, причина) => {
  сделано++;
  log(`  ${годно ? '✓' : '✗'} ${имя}${замер ? '  — ' + замер : ''}${!годно && причина ? '  (' + причина + ')' : ''}`);
  if (!годно) note(`${имя}: ${причина || замер || 'не сошлось'}`);
};

let живой = false;
try { живой = (await fetch(`${U}/health`)).ok; } catch { /* нет */ }
if (!живой) {
  console.log(`сервера на ${PORT} нет — мерить нечего`);
  console.log(`подними: PORT=${PORT} node server/server.js`);
  process.exit(1);
}

const { installHeadless } = await import('../src/core/headless.js');
installHeadless();
globalThis.location = { origin: `http://localhost:${PORT}`, protocol: 'http:', host: `localhost:${PORT}`, search: '' };
const { initProps } = await import('../src/art/props.js');
const { bakeAllMonsters } = await import('../src/art/sprites.js');
initProps();
bakeAllMonsters();

const { Game } = await import('../src/game.js');
const wallet = await import('../src/core/wallet.js');
const net = (await import('../src/core/net.js')).default || (await import('../src/core/net.js')).net;

const пусто = { canvas: { width: 480, height: 270 }, save() {}, restore() {}, drawImage() {}, fillRect() {},
  clearRect() {}, beginPath() {}, fill() {}, stroke() {}, translate() {}, scale() {}, measureText: () => ({ width: 10 }),
  fillText() {}, setTransform() {}, createLinearGradient: () => ({ addColorStop() {} }) };

try { localStorage.clear(); } catch { /* нечего */ }
const g = new Game(пусто, { w: 480, h: 270 }, пусто);
g.newGame();
await wallet.playAsGuest();
const вход = await g.goOnline();
log(`вход в общий мир: ${вход}`);
if (вход !== 'online') {
  console.log('в комнату не вошли — мерить нечего');
  process.exit(1);
}
await wait(1800);
g.applyMe();

/** Дождаться свежего `me` от комнаты: она шлёт его каждый четвёртый такт. */
async function отКомнаты(мс = 1500) {
  const было = net.me;
  for (let i = 0; i < мс / 50; i++) { await wait(50); if (net.me !== было) break; }
  g.applyMe();
  return net.me;
}

// ══════════════════════════════ очки развития

log('');
log('── очки развития');
{
  // Очки даёт уровень, а уровень в общем мире даёт комната. Просим её поднять
  // нас честно нечем, поэтому смотрим на то, что есть: если очков нет — правило
  // всё равно проверяемо, комната обязана ответить отказом, а не промолчать.
  const очковБыло = g.player.statPoints || 0;
  const силаБыла = g.player.str;
  log(`  очков ${очковБыло}, сила ${силаБыла}`);

  g.player.statPoints = очковБыло;   // ничего не подкручиваем: играем как есть
  const ответ = await new Promise((готово) => {
    let ответил = false;
    net.onDeal = (m) => { if (m && m.act === 'stat') { ответил = true; готово(m); } };
    const ушло = net.торг({ t: 'stat', k: 'str' });
    if (!ушло) { готово({ нетКанала: true }); return; }
    setTimeout(() => { if (!ответил) готово(null); }, 2000);
  });
  net.onDeal = null;
  log(`  на «вложить очко в силу» комната ответила: ${ответ ? JSON.stringify(ответ).slice(0, 90) : 'молчание'}`);
  проверить('комната знает про трату очков', !!ответ && !ответ.нетКанала,
    ответ ? (ответ.нетКанала ? 'канал закрыт' : (ответ.why || ответ.what || 'ответ есть')) : 'комната промолчала',
    'сообщения о трате очков в протоколе нет: «+» поднимает стат только на экране, и через миг всё возвращается');

  // Отвечать мало — правило должно исполняться. Выдуманное имя стата и
  // настоящее обязаны получить РАЗНЫЕ отказы: значит проверка дошла до самой
  // `spendStat`, а не остановилась на маршрутизации.
  const чушь = await new Promise((готово) => {
    net.onDeal = (m) => { if (m && m.act === 'stat') готово(m); };
    net.торг({ t: 'stat', k: 'ловкорукость' });
    setTimeout(() => готово(null), 2000);
  });
  net.onDeal = null;
  log(`  на выдуманный стат: ${чушь ? чушь.why : 'молчание'}`);
  проверить('правило исполняется, а не только маршрутизируется',
    !!(чушь && ответ && чушь.why && ответ.why && чушь.why !== ответ.why),
    `«${(ответ && ответ.why) || '—'}» против «${(чушь && чушь.why) || '—'}»`,
    'комната отвечает одинаково на всё — значит до правила дело не доходит');

  // И местная кнопка не должна двигать стат в общем мире, что бы ни было.
  // Очки герою мира взять неоткуда: их даёт уровень, а уровень даёт комната.
  // Поэтому кладём их ТОЛЬКО клиенту — ровно то, что происходит в жизни, когда
  // он показывает свои числа вместо присланных. Если кнопка сработает, значит
  // клиент решает сам, и комната об этом не узнает.
  g.player.statPoints = 3;
  const силаДо = g.player.str;
  if (typeof g.вложитьОчко === 'function') g.вложитьОчко('str');
  else g.player.spendStat('str');
  проверить('клиент сам стат не поднимает', g.player.str === силаДо,
    `сила ${силаДо}→${g.player.str} при трёх очках на экране`,
    'стат вырос на экране, а комната об этом не знает — вернётся при первом же обновлении');
}

// ══════════════════════════════ зелья

log('');
log('── зелья');
{
  // Зелье покупаем у комнаты: у героя мира его нет, а подкладывать своё нельзя
  // — рюкзак в общем мире ведёт она, и подложенное исчезнет на первом обновлении.
  const прилавок = await new Promise((готово) => {
    net.onShop = (m) => готово(m);
    net.торг({ t: 'shop', npc: 'alchemy' });
    setTimeout(() => готово(null), 2000);
  });
  net.onShop = null;
  const товар = ((прилавок && прилавок.stock) || []).find((x) => x && x.heal);
  log(`  прилавок алхимика: ${((прилавок && прилавок.stock) || []).length} товаров, лечебное ${товар ? '«' + товар.name + '»' : 'не нашлось'}`);
  if (товар) {
    const купля = await new Promise((готово) => {
      net.onDeal = (m) => { if (m && m.act === 'buy') готово(m); };
      net.торг({ t: 'buy', npc: 'alchemy', slot: товар.slot });
      setTimeout(() => готово(null), 2000);
    });
    net.onDeal = null;
    log(`  покупка: ${купля ? (купля.ok ? 'куплено «' + купля.name + '»' : купля.why) : 'молчание'}`);
    await wait(900);
  }
  const зелье = (g.player.inventory || []).find((x) => x && x.heal);
  if (!зелье) {
    note('зелья добыть не удалось — правило про зелья не проверено');
    log('  ✗ зелья нет, мерить нечего');
  } else {
    // Отнимаем здоровье у комнаты честно: просим её же. Прямой правки хватило бы
    // для показа, но комната бы о ней не знала, и лечение мерить было бы не от
    // чего.
    const доHp = g.player.hp;
    log(`  зелье «${зелье.name}» (+${зелье.heal}), здоровье ${доHp}/${g.player.maxHp}, зелий в рюкзаке ${зелье.count || 1}`);

    // Зовём игру, а не сеть: правило про общий мир живёт в `Game.usePotion`, и
    // проверять надо его. Первая версия слала сообщение сама и потому не
    // заметила мутацию, снявшую клиентскую охрану, — стенд мерил протокол
    // вместо правила.
    const ответ = await new Promise((готово) => {
      let ответил = false;
      net.onDeal = (m) => { if (m && m.act === 'potion') { ответил = true; готово(m); } };
      g.usePotion(зелье);
      setTimeout(() => { if (!ответил) готово(null); }, 2000);
    });
    net.onDeal = null;
    log(`  на «выпить» при полном здоровье: ${ответ ? JSON.stringify(ответ).slice(0, 90) : 'молчание'}`);
    проверить('комната знает про зелья', !!ответ && !ответ.нетКанала,
      ответ ? (ответ.нетКанала ? 'канал закрыт' : (ответ.why || ответ.what || 'ответ есть')) : 'комната промолчала',
      'зелье пьётся у клиента: лечит несуществующее здоровье и возвращается в рюкзак при обновлении');

    // Отказ при полном здоровье — половина дела. Настоящая проверка — что
    // выпитое лечит и уходит из рюкзака. Урон берём у мира: едем в лес и стоим,
    // пока по нам не ударят. Подкручивать здоровье у клиента бессмысленно —
    // считает его комната.
    log('  едем в лес за уроном…');
    net.travel({ kind: 'biome', id: 'forest' });
    await wait(2500);
    let ранены = false;
    for (let i = 0; i < 120; i++) {
      await wait(250);
      const мой = net.myServerState();
      if (мой && мой.hp < мой.mhp) { ранены = true; break; }
    }
    const мой = net.myServerState();
    log(`  здоровье в лесу: ${мой ? мой.hp + '/' + мой.mhp : '?'}${ранены ? '' : ' — по нам так и не ударили'}`);
    if (!ранены) {
      log('  · урона не дождались — удачное лечение этот прогон не мерили');
    } else {
      const hpДо = мой.hp;
      const зельеТеперь = (g.player.inventory || []).find((x) => x && x.heal);
      const питьё = await new Promise((готово) => {
        net.onDeal = (m) => { if (m && m.act === 'potion') готово(m); };
        g.usePotion(зельеТеперь || зелье);
        setTimeout(() => готово(null), 2500);
      });
      net.onDeal = null;
      await wait(900);
      const после = net.myServerState();
      const осталось = (g.player.inventory || []).filter((x) => x && x.heal).reduce((s2, x) => s2 + (x.count || 1), 0);
      log(`  выпили: ${питьё ? (питьё.ok ? 'да, +' + питьё.heal : питьё.why) : 'молчание'}; здоровье ${hpДо} → ${после ? после.hp : '?'}, зелий осталось ${осталось}`);
      проверить('выпитое лечит по-настоящему', !!(питьё && питьё.ok) && !!после && после.hp > hpДо,
        `${hpДо} → ${после ? после.hp : '?'}`,
        'комната приняла зелье, но здоровья не прибавила');
      проверить('выпитое уходит из рюкзака', осталось === 0,
        `${осталось} осталось`,
        'зелье возвращается на пояс при первом же обновлении рюкзака');
    }
  }
}

g.goOffline();
console.log('');
console.log(`проверок: ${сделано}`);
if (problems.length) {
  console.log(`найдено: ${problems.length}`);
  for (const p of problems) console.log('  ' + p);
  process.exit(1);
}
console.log('ПРОБЛЕМ НЕ НАЙДЕНО');
process.exit(0);
