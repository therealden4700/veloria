// Одиночное сохранение не должно погибнуть от захода в общий мир.
//
//   node tools/save-online-check.js
//
// Найдено проверкой готовности к релизу, и это единственное из найденного, чего
// игрок не сможет себе вернуть.
//
// Герой общего мира и герой одиночной игры — разные герои. Первого ведёт
// комната и хранит у себя, второго ведёт клиент и хранит в браузере. Но живут
// они в одном и том же объекте `game.player`: войдя в общий мир, клиент
// подменяет рюкзак, снаряжение, золото и опыт тем, что прислала комната. А
// `save()` про сеть ничего не знает и пишет этого — уже чужого — героя в тот же
// одиночный слот. Автосейвом каждые сорок пять секунд.
//
// Замер до починки: офлайн-герой 30-го уровня с полным рюкзаком после одного
// захода в общий город и одного автосейва остаётся в сохранении тридцатым, но
// без вещей и без золота. Резервные копии перезапишутся следующим автосейвом,
// серверная копия — тем же `pushCharacter`.
//
//   node tools/save-online-check.js [порт]
//
// Стенд входит в НАСТОЯЩУЮ комнату гостем и выходит из неё. Первая версия
// подделывала состояние сети (`net.state = 'online'`) и этим себя обманула:
// снимок офлайн-героя кладётся в `goOnline`, мимо которого она проходила, — и
// проверка «после выхода вернулся свой герой» краснела на пустом месте, хотя
// правило было написано верно. Через настоящий вход такого не случится.
//
// ЧЕГО ЭТОТ СТЕНД НЕ МЕРЯЕТ. Саму сеть: она проверяется другими стендами. И
// зрелище — что игрок при этом видит на экране.

const { installHeadless } = await import('../src/core/headless.js');
installHeadless();

const problems = [];
const note = (s) => problems.push(s);
const log = (s) => console.log(s);
let сделано = 0;
const проверить = (имя, годно, замер, причина) => {
  сделано++;
  log(`  ${годно ? '✓' : '✗'} ${имя}${замер ? '  — ' + замер : ''}${!годно && причина ? '  (' + причина + ')' : ''}`);
  if (!годно) note(`${имя}: ${причина || замер || 'не сошлось'}`);
};

// Зона строится из настоящего реквизита: без запекания генератор не знает его
// габаритов и падает на первом же доме.
const { initProps } = await import('../src/art/props.js');
const { bakeAllMonsters } = await import('../src/art/sprites.js');
initProps();
bakeAllMonsters();

// `goOnline` спрашивает адрес комнаты у страницы. Страницы здесь нет — даём
// ровно то, что дал бы браузер, и ничего больше.
const PORT = Number(process.argv[2] || 3000);
globalThis.location = { origin: `http://localhost:${PORT}`, protocol: 'http:', host: `localhost:${PORT}`, search: '' };

const { Game } = await import('../src/game.js');
const { makeItem } = await import('../src/systems/items.js');
const store = await import('../src/core/save.js');
const wallet = await import('../src/core/wallet.js');
const net = (await import('../src/core/net.js')).default || (await import('../src/core/net.js')).net;

/** Игра без экрана: холсты подменяет `headless`, а нам нужен только её состав. */
function завестиИгру() {
  const пусто = { canvas: { width: 480, height: 270 }, save() {}, restore() {}, drawImage() {}, fillRect() {},
    clearRect() {}, beginPath() {}, fill() {}, stroke() {}, translate() {}, scale() {}, measureText: () => ({ width: 10 }),
    fillText() {}, setTransform() {}, createLinearGradient: () => ({ addColorStop() {} }) };
  return new Game(пусто, { w: 480, h: 270 }, пусто);
}

/** Богатый герой одиночной игры: тридцатый уровень, вещи, золото. */
function нажитое(g) {
  const p = g.player;
  p.level = 30; p.gold = 5000;
  p.inventory.length = 0;
  for (let i = 0; i < 6; i++) p.addItem(makeItem({ kind: i % 2 ? 'weapon' : 'armor', level: 30, rarity: 'epic' }));
  p.equipment.weapon = makeItem({ kind: 'weapon', level: 30, rarity: 'legendary' });
  return { уровень: p.level, золото: p.gold, вещей: p.inventory.length, оружие: !!p.equipment.weapon };
}

const слепокСлота = () => {
  const s = store.loadGame();
  const p = s && s.player;
  return p ? { уровень: p.level, золото: p.gold, вещей: (p.inventory || []).length, оружие: !!(p.equipment && p.equipment.weapon) } : null;
};

// ══════════════════════════════ офлайн-герой нажит и записан

log('── нажитое офлайн');
try { localStorage.clear(); } catch { /* нечего чистить */ }

const g = завестиИгру();
g.newGame();
const было = нажитое(g);
g.save({ fresh: true });
const вСлоте = слепокСлота();
log(`  герой: ур. ${было.уровень}, золото ${было.золото}, вещей ${было.вещей}, оружие ${было.оружие ? 'есть' : 'нет'}`);
проверить('одиночный слот записан', !!вСлоте && вСлоте.уровень === 30 && вСлоте.вещей === 6,
  вСлоте ? `ур. ${вСлоте.уровень}, вещей ${вСлоте.вещей}, золото ${вСлоте.золото}` : 'слота нет',
  'мерить дальше нечего — сохранение не работает и до общего мира');

// ══════════════════════════════ вход в общий мир

log('');
log('── вход в общий мир');

await wallet.playAsGuest();
const ответ = await g.goOnline();
log(`  goOnline вернул: ${ответ}`);
if (ответ !== 'online') {
  note(`в комнату не вошли (${ответ}) — правило не проверено`);
  console.log(`\nпроверок: ${сделано}\nнайдено: ${problems.length}`);
  for (const p of problems) console.log('  ' + p);
  process.exit(1);
}
// Ждём, пока комната пришлёт своё: рюкзак и состояние приходят не мгновенно.
await new Promise((r) => setTimeout(r, 1500));
g.applyMe();

const вОбщем = { уровень: g.player.level, золото: g.player.gold, вещей: g.player.inventory.length, оружие: !!g.player.equipment.weapon };
log(`  герой мира: ур. ${вОбщем.уровень}, золото ${вОбщем.золото}, вещей ${вОбщем.вещей}, оружие ${вОбщем.оружие ? 'есть' : 'нет'}`);
проверить('комната действительно подменила героя', вОбщем.вещей === 0 && вОбщем.золото === 40,
  `вещей ${вОбщем.вещей}, золото ${вОбщем.золото}`,
  'подмена не разыграна — дальше проверять нечего');

// ══════════════════════════════ автосейв в общем мире

log('');
log('── автосейв, пока мы в общем мире');
const записалось = g.save();
const после = слепокСлота();
log(`  save() вернул ${записалось}; в слоте: ур. ${после.уровень}, золото ${после.золото}, вещей ${после.вещей}, оружие ${после.оружие ? 'есть' : 'нет'}`);

проверить('одиночное сохранение цело',
  после.вещей === было.вещей && после.золото === было.золото && после.оружие === было.оружие,
  `вещей ${было.вещей}→${после.вещей}, золото ${было.золото}→${после.золото}, оружие ${было.оружие ? 'есть' : 'нет'}→${после.оружие ? 'есть' : 'нет'}`,
  'заход в общий мир стёр нажитое офлайн — вернуть это игроку нечем');

// ══════════════════════════════ выход обратно

log('');
log('── вышли из общего мира');
g.goOffline();

const вернулся = { уровень: g.player.level, золото: g.player.gold, вещей: g.player.inventory.length, оружие: !!g.player.equipment.weapon };
log(`  герой после выхода: ур. ${вернулся.уровень}, золото ${вернулся.золото}, вещей ${вернулся.вещей}`);
проверить('после выхода вернулся свой герой',
  вернулся.вещей === было.вещей && вернулся.золото === было.золото,
  `вещей ${вернулся.вещей} из ${было.вещей}, золото ${вернулся.золото} из ${было.золото}`,
  'из общего мира вышли чужим героем — и первый же автосейв запишет его');

g.save();
const итог = слепокСлота();
log(`  после автосейва вне сети: ур. ${итог.уровень}, золото ${итог.золото}, вещей ${итог.вещей}`);
проверить('сохранение цело и после выхода',
  итог.вещей === было.вещей && итог.золото === было.золото,
  `вещей ${итог.вещей} из ${было.вещей}, золото ${итог.золото} из ${было.золото}`,
  'обратный порядок губит слот так же, как прямой');

console.log('');
console.log(`проверок: ${сделано}`);
if (problems.length) {
  console.log(`найдено: ${problems.length}`);
  for (const p of problems) console.log('  ' + p);
  process.exit(1);
}
console.log('ПРОБЛЕМ НЕ НАЙДЕНО');
process.exit(0);
