/** Своя учётка на каждого: прогресс должен быть раздельным, иначе мерить нечего. */
async function войти() {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const address = base58(Buffer.from(publicKey.export({ format: 'jwk' }).x, 'base64url'));
  const { nonce } = await j('/auth/nonce', { address });
  const msg = buildMessage(nonce, `localhost:${PORT}`, new Date().toISOString());
  const v = await j('/auth/verify', {
    address, message: msg,
    signature: sign(null, Buffer.from(msg, 'utf8'), privateKey).toString('hex'),
  });
  if (!v.ok) throw new Error('вход не удался: ' + JSON.stringify(v));
  return v.token;
}

async function подключиться(token, имя, at) {
  const c = {
    имя, snaps: [], пришло: [], события: [], pid: null, закрыт: null,
    ws: new WebSocket(`ws://localhost:${PORT}/`),
  };
  await new Promise((done, fail) => {
    c.ws.addEventListener('open', () => c.ws.send(JSON.stringify({ t: 'hello', token, name: имя, at })));
    c.ws.addEventListener('close', (e) => {
      c.закрыт = `${e.code} ${e.reason || ''}`.trim();
      if (c.пульс) clearInterval(c.пульс);
      fail(new Error(`комната закрыла связь: ${c.закрыт}`));
    });
    c.ws.addEventListener('message', (m) => {
      const msg = JSON.parse(m.data);
      if (msg.t === 'snap') {
        c.snaps.push(msg); if (c.snaps.length > 20) c.snaps.shift();
        for (const e of msg.ev || []) c.события.push(e);
        return;
      }
      c.пришло.push(msg);
      if (msg.t === 'me') c.me = msg;
      if (msg.t === 'журнал') c.журнал = msg.quests;
      if (msg.t === 'welcome') { c.pid = msg.pid; c.snaps.length = 0; done(); }
    });
    setTimeout(() => fail(new Error('нет welcome за 5 с')), 5000);
  });
  // Пульс.
  //
  // В этом стенде один бот ждёт, пока дерётся другой, — и первая версия на этом
  // потерялась целиком: комната отключает молчащих через пятнадцать секунд
  // (`DEAD_MS`), а ждать приходится под минуту. Второй бот оказывался выкинут,
  // снимки переставали приходить, его положение в стенде замирало на точке
  // входа — и «за двадцать пять секунд ни одного взмаха» выглядело как
  // поломанное правило вклада. Настоящий клиент шлёт ввод каждый кадр; здесь
  // хватит пустого ввода раз в три секунды.
  c.пульс = setInterval(() => {
    try { c.ws.send(JSON.stringify({ t: 'input', s: [] })); } catch { /* уже нет */ }
  }, 3000);

  c.спросить = async (msg, ждём) => {
    const было = c.пришло.length;
    c.ws.send(JSON.stringify(msg));
    for (let i = 0; i < 40; i++) {
      await wait(50);
      const н = c.пришло.slice(было).find((x) => x.t === ждём);
      if (н) return н;
    }
    return null;
  };
  return c;
}

