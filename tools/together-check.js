/**
 * Ударить и вернуть, сколько дошло.
 *
 * Бить «на 99999» нельзя, и это стоило одного ложного прогона: `записатьВклад`
 * запоминает нанесённое ДО того, как `killEnemy` обрежет здоровье до нуля, —
 * значит добивающий перебор целиком уходит в долю бьющего, и она становится
 * почти стопроцентной. Держим удар в пределах остатка.
 */
const ударить = (w, e, сколько, кем, ещё) => {
  const было = e.hp;
  w.damageEnemy(e, Math.max(1, Math.min(сколько, e.hp + 2)), { ...(ещё || {}), ...(кем ? { by: кем } : {}) });
  return Math.max(0, было - Math.max(0, e.hp));
};
