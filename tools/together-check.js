async function шагать(c, dx, dy, мс) {
  const t0 = Date.now(); let было = t0;
  while (Date.now() - t0 < мс) {
    await wait(50);
    const now = Date.now(), dt = (now - было) / 1000; было = now;
    c.ws.send(JSON.stringify({ t: 'input', s: [[dx, dy, dt]], f: Math.atan2(dy, dx) }));
  }
}
async function подойти(c, предел, к, вплотную = 14) {
  const t0 = Date.now();
  while (Date.now() - t0 < предел) {
    const m = я(c), t = к();
    if (!m || !t) return false;
    const dx = t.x - m.x, dy = t.y - m.y, d = Math.hypot(dx, dy) || 1;
    if (d < вплотную) return true;
    await шагать(c, dx / d, dy / d, 150);
  }
  return false;
}

/**
 * Подойти к врагу, которого может не быть в снимке.
 *
 * Видно 420 пикселей, и цель на самой границе то попадает в снимок, то нет —
 * первый прогон стенда на этом и споткнулся: «цели нет», хотя она была. Идём
 * по последнему известному месту, пока цель не покажется, дальше ведём по ней.
 */
async function подойтиКврагу(c, предел, i, где, вплотную = 14) {
  const t0 = Date.now();
  const место = { ...где };
  // Идти прямо на цель мало: между ботом и врагом бывает дерево, и упор в него
  // выглядит как «за двадцать пять секунд ни одного взмаха». Один прогон
  // мутации на этом и потерялся. Если расстояние перестало сокращаться —
  // берём вбок и обходим.
  let лучшее = Infinity, застрял = 0;
  while (Date.now() - t0 < предел) {
    const m = я(c);
    if (!m || m.hp <= 0) return false;
    const t = враг(c, i);
    if (t) { место.x = t.x; место.y = t.y; }
    const dx = место.x - m.x, dy = место.y - m.y, d = Math.hypot(dx, dy) || 1;
    if (t && d < вплотную) return true;
    if (!t && d < 10) return false;          // дошли до места, а его там нет
    if (d < лучшее - 2) { лучшее = d; застрял = 0; } else застрял++;
    if (ГРОМКО) log(`    · ${c.имя} @${Math.round(m.x)},${Math.round(m.y)} → ${Math.round(место.x)},${Math.round(место.y)} = ${Math.round(d)}${t ? '' : ' (цели не видно)'}${застрял ? ' застрял×' + застрял : ''}`);
    if (застрял >= 8) {
      застрял = 0; лучшее = Infinity;
      const бок = (Date.now() % 2 === 0) ? 1 : -1;   // сторону чередуем
      await шагать(c, (-dy / d) * бок, (dx / d) * бок, 700);
      continue;
    }
    await шагать(c, dx / d, dy / d, 150);
  }
  return false;
}

/**
 * Найти цель для совместного боя: целую и, по возможности, ту, которую просит
 * задание. Смотрим не один снимок, а несколько: на границе видимости враг
 * мигает, и одного кадра мало.
 */
async function найтиЦель(c, вид, секунд = 6) {
  const виденные = new Map();
  const t0 = Date.now();
  while (Date.now() - t0 < секунд * 1000) {
    for (const e of ((снимок(c) || {}).enemies || [])) {
      if (e.hp < e.mx) continue;                       // уже начатых не берём
      if (!виденные.has(e.i)) виденные.set(e.i, e);
    }
    await wait(200);
  }
  const m = я(c);
  const близость = (e) => Math.hypot(e.x - m.x, e.y - m.y);
  const свои = [...виденные.values()].filter((e) => e.k === вид).sort((a, b) => близость(a) - близость(b));
  if (свои.length) return { враг: свои[0], поЗаданию: true };
  const любые = [...виденные.values()].sort((a, b) => близость(a) - близость(b));
  return любые.length ? { враг: любые[0], поЗаданию: false } : null;
}
/**
 * Бить цель, пока не сработает условие остановки.
 *
 * Возвращает не только число взмахов, но и причину остановки. Без причины
 * первый же прогон мутации соврал: бот не ударил ни разу, стенд показал «цель не
 * умерла», и это выглядело как поломанное правило, хотя бота просто убили по
 * дороге. Прибор, который не говорит, почему он молчит, хуже отсутствующего.
 */
async function бить(c, i, стоп, предел = 25000) {
  const t0 = Date.now();
  let взмахов = 0, пусто = 0;
  while (Date.now() - t0 < предел) {
    const m = я(c);
    if (!m) return { взмахов, почему: 'меня нет в снимке' };
    if (m.hp <= 0) return { взмахов, почему: 'убит по дороге' };
    const t = враг(c, i);
    if (!t) {
      // Цель мигает на границе видимости — это не повод бросать бой.
      if (++пусто > 10) return { взмахов, почему: 'цель пропала из снимка' };
      await wait(120);
      continue;
    }
    пусто = 0;
    if (стоп(t)) return { взмахов, почему: 'дошли до отметки' };
    if (Math.hypot(t.x - m.x, t.y - m.y) > 20) {
      if (!await подойтиКврагу(c, 3000, i, t)) continue;
    }
    c.ws.send(JSON.stringify({ t: 'swing', combo: взмахов % 3, f: Math.atan2(t.y - m.y, t.x - m.x) }));
    взмахов++;
    await wait(260);
  }
  return { взмахов, почему: 'вышло время' };
}
