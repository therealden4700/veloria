// Играется ли игра пальцем.
//
//   node tools/touch-check.js
//
// Игра раздаётся ссылкой, а ссылку на браузерную игру чаще открывают с
// телефона, чем с настольного. Значит телефон — это главный вход, а не запасной.
//
// Найдено проверкой готовности к релизу: сенсорный слой попадает только по
// гнёздам пояса — удар, руны, рывок, зелье. Больше на экране нет ни одной
// сенсорной цели. Всё остальное осталось на клавиатуре: заговорить с торговцем,
// открыть сундук, войти в проход, открыть рюкзак, журнал, паузу. Человек с
// телефона может ходить и бить — и всё.
//
// Здесь сверяются два списка: что игра умеет с клавиатуры и что из этого можно
// достать пальцем. Списки берутся из самих файлов, а не переписываются сюда:
// вторая копия однажды разойдётся с первой и стенд соврёт.
//
// ЧЕГО ЭТОТ СТЕНД НЕ МЕРЯЕТ. Удобство: попадает ли палец, не закрывает ли рука
// половину экрана — это видно только на живом телефоне. И меню: там касания
// работают сами, браузер делает из них щелчки.

const problems = [];
const note = (s) => problems.push(s);
const log = (s) => console.log(s);
let сделано = 0;
const проверить = (имя, годно, замер, причина) => {
  сделано++;
  log(`  ${годно ? '✓' : '✗'} ${имя}${замер ? '  — ' + замер : ''}${!годно && причина ? '  (' + причина + ')' : ''}`);
  if (!годно) note(`${имя}: ${причина || замер || 'не сошлось'}`);
};

const { installHeadless } = await import('../src/core/headless.js');
installHeadless();
const { initProps } = await import('../src/art/props.js');
const { bakeAllMonsters } = await import('../src/art/sprites.js');
initProps();
bakeAllMonsters();

const { Game } = await import('../src/game.js');

// Холст-пустышка: рисовать некому, а разметку гнёзд HUD складывает всё равно —
// именно по ней и попадает палец.
const мимо = new Proxy({}, {
  get(_, k) {
    if (k === 'canvas') return { width: 480, height: 270 };
    if (k === 'measureText') return () => ({ width: 8 });
    if (k === 'createLinearGradient' || k === 'createRadialGradient') return () => ({ addColorStop() {} });
    if (k === 'getImageData') return () => ({ data: new Uint8ClampedArray(4) });
    if (k === 'createImageData') return () => ({ data: new Uint8ClampedArray(4) });
    return () => {};
  },
  set() { return true; },
});

const g = new Game(мимо, { w: 480, h: 270 }, мимо);
g.newGame();
// Изображаем сенсорное устройство. Этот же флаг ставит `attachTouch`, когда
// видит палец: HUD рисует сенсорные кнопки только по нему, иначе на настольном
// экране был бы лишний шум.
g.input.сенсорный = true;

// ══════════════════════════════ что вообще есть на телефоне

log('── что достаётся пальцем');

// Рисуем кадр: HUD при этом и складывает разметку сенсорных целей.
g.update(1 / 60);
g.draw();

const цели = (g.hud && g.hud.touchSlots) || [];
const действия = [...new Set(цели.map((s) => s.action))];
log(`  сенсорных целей: ${цели.length} → ${действия.join(', ') || 'нет ни одной'}`);
проверить('сенсорные цели вообще есть', цели.length > 0,
  `${цели.length}`, 'пальцем не сделать ничего');

// Без чего с телефона не пройти дальше первых минут. Список короткий нарочно:
// это не «всё, что есть на клавиатуре», а «без чего игра не игра».
// `interact` сюда не входит намеренно: оно по природе появляется только когда
// есть с чем взаимодействовать, и постоянная кнопка, бездействующая почти всё
// время, была бы хуже. Его проверяет отдельный раздел ниже — по подсказке,
// которую игра в такую минуту и показывает.
const НУЖНО = [
  ['attack', 'ударить'],
  ['inventory', 'рюкзак и снаряжение'],
  // Не `pause`, а `cancel`: меню паузы читает именно его. `Escape` в раскладке
  // значится обоими, и `pause` не читает никто — из-за этого кнопка с
  // «правильным» именем не открывала ничего.
  ['cancel', 'пауза и настройки'],
];
log('');
for (const [act, зачем] of НУЖНО) {
  проверить(`пальцем можно: ${зачем}`, действия.includes(act), act,
    `с телефона это действие недоступно вовсе — только с клавиатуры`);
}

// ══════════════════════════════ настольный экран не изменился

log('');
log('── на настольном кнопок быть не должно');
{
  // Обратная сторона правила. Кнопки — плата за отсутствие клавиатуры; там, где
  // клавиатура есть, они лишний шум поверх и без того плотного экрана.
  const d = new Game(мимо, { w: 480, h: 270 }, мимо);
  d.newGame();
  d.input.сенсорный = false;
  d.update(1 / 60);
  d.draw();
  const наСтоле = [...new Set(((d.hud && d.hud.touchSlots) || []).map((x) => x.action))];
  log(`  целей на настольном: ${наСтоле.join(', ') || 'нет'}`);
  проверить('сенсорных кнопок на настольном нет',
    !наСтоле.includes('inventory') && !наСтоле.includes('cancel'),
    наСтоле.join(', ') || 'ни одной',
    'кнопки для пальца нарисованы там, где есть клавиатура');
}

// ══════════════════════════════ подсказка «E» должна быть кнопкой

log('');
log('── подсказка взаимодействия');
{
  // Когда игра показывает «E — поговорить», на телефоне это должно быть местом,
  // куда можно ткнуть. Иначе подсказка обещает то, чего пальцем не сделать.
  g.prompt = { label: 'поговорить', key: 'E', color: '#ffd06a' };
  g.draw();
  const послеПодсказки = ((g.hud && g.hud.touchSlots) || []).some((s) => s.action === 'interact');
  проверить('пока висит подсказка, по ней можно ткнуть', послеПодсказки,
    послеПодсказки ? 'цель есть' : 'цели нет',
    'игра пишет «E — поговорить» тому, у кого нет клавиши E');
  g.prompt = null;
}

console.log('');
console.log(`проверок: ${сделано}`);
if (problems.length) {
  console.log(`найдено: ${problems.length}`);
  for (const p of problems) console.log('  ' + p);
  process.exit(1);
}
console.log('ПРОБЛЕМ НЕ НАЙДЕНО');
process.exit(0);
