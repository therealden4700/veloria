// Связь: обрыв должен быть виден, отказ — назван, а живой сокет — считаться живым.
//
//   node tools/link-check.js [порт]
//
// Три находки проверки готовности к релизу об одном узле.
//
// Первая. Комната отказывает не ответом, а закрытием сокета: 1008 «нужен токен
// входа», 1013 «людно». А обещание `net.connect` разрешается только на
// `welcome` и в `fail()`, который зовут из `onerror` и из сторожа на пять
// секунд. `onclose` обещание не трогает — и заодно переводит состояние в
// `offline`, из-за чего сторож тоже не срабатывает. Итог: игрок жмёт «В общий
// город», и НЕ ПРОИСХОДИТ НИЧЕГО. Ни сообщения, ни экрана, и повторное нажатие
// такое же.
//
// Вторая. Комната считает живым того, кто шлёт игровые сообщения (`lastSeen`), а
// не того, чей сокет отвечает на ping (`lastPong` пишется, но не читается).
// Клиент шлёт ввод из кадрового цикла на `requestAnimationFrame`, а в свёрнутой
// вкладке тот не тикает — замерено, ноль кадров за две секунды. Пятнадцать
// секунд в фоне — и игрока выкидывают, хотя связь была цела.
//
// Третья. `ws.onclose` только ставит `state = 'offline'` и никому не сообщает.
// Игра продолжается как одиночная: соседи исчезли, бой идёт, опыт капает — и
// ничего из этого в общий мир не попадёт.
//
// ЧЕГО ЭТОТ СТЕНД НЕ МЕРЯЕТ. Настоящую свёрнутую вкладку: здесь молчание
// клиента изображается тем, что он просто не шлёт ввод, — а это ровно то же
// самое с точки зрения комнаты.

const PORT = Number(process.argv[2] || 3000);
const U = `http://localhost:${PORT}`;
const problems = [];
const note = (s) => problems.push(s);
const log = (s) => console.log(s);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
let сделано = 0;
const проверить = (имя, годно, замер, причина) => {
  сделано++;
  log(`  ${годно ? '✓' : '✗'} ${имя}${замер ? '  — ' + замер : ''}${!годно && причина ? '  (' + причина + ')' : ''}`);
  if (!годно) note(`${имя}: ${причина || замер || 'не сошлось'}`);
};

let живой = false;
try { живой = (await fetch(`${U}/health`)).ok; } catch { /* нет */ }
if (!живой) {
  console.log(`сервера на ${PORT} нет — мерить нечего`);
  console.log(`подними: PORT=${PORT} node server/server.js`);
  process.exit(1);
}

const { installHeadless } = await import('../src/core/headless.js');
installHeadless();
globalThis.location = { origin: `http://localhost:${PORT}`, protocol: 'http:', host: `localhost:${PORT}`, search: '' };
const net = (await import('../src/core/net.js')).default || (await import('../src/core/net.js')).net;
const гость = async () => (await (await fetch(`${U}/auth/verify`, {
  method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ guest: true }),
})).json()).token;

// ══════════════════════════════ отказ комнаты должен быть назван

log('── отказ комнаты');
{
  // Комната закроет сокет: токена такого нет. Настоящий игрок попадает сюда
  // после перезапуска сервера — сессии живут в памяти, а токен в браузере.
  const t0 = Date.now();
  const гонка = await Promise.race([
    net.connect(`ws://localhost:${PORT}/`, { name: 'Отвергнутый', token: 'нет-такого-токена' }),
    wait(7000).then(() => 'ЗАВИСЛО'),
  ]);
  const ждали = Date.now() - t0;
  log(`  connect вернул ${гонка === 'ЗАВИСЛО' ? 'НИЧЕГО за 7 с' : JSON.stringify(гонка)} за ${ждали} мс, ошибка: ${net.error || '—'}`);
  проверить('на отказ комнаты обещание разрешается', гонка !== 'ЗАВИСЛО',
    гонка === 'ЗАВИСЛО' ? 'не разрешилось за 7 с' : `${ждали} мс`,
    'кнопка «В общий город» молчит навсегда: ни сообщения, ни экрана');
  проверить('причина отказа названа', !!net.error && net.error !== 'нет связи с комнатой',
    net.error || 'причины нет',
    'игроку нечего показать — он не узнает, что надо войти заново');
  net.disconnect();
  await wait(300);
}

// ══════════════════════════════ молчащий, но живой сокет

log('');
log('── вкладка в фоне: сокет жив, ввода нет');
{
  // Токен берём ДО сокета. Иначе `await` успевает пропустить событие `open`,
  // обработчик вешается на уже открытое соединение, `hello` не уходит вовсе — и
  // стенд краснеет на «нет welcome», не измерив ничего.
  const token = await гость();
  const c = { снимков: 0, закрыт: null, ws: new WebSocket(`ws://localhost:${PORT}/`) };
  await new Promise((ok, fail) => {
    c.ws.addEventListener('open', () => c.ws.send(JSON.stringify({ t: 'hello', token, name: 'Свёрнутый' })));
    c.ws.addEventListener('close', (e) => { c.закрыт = `${e.code} ${e.reason || ''}`.trim(); fail(new Error(c.закрыт)); });
    c.ws.addEventListener('message', (m) => {
      const x = JSON.parse(m.data);
      if (x.t === 'snap') c.снимков++;
      if (x.t === 'welcome') ok();
    });
    setTimeout(() => fail(new Error('нет welcome')), 5000);
  });

  // Двадцать секунд ничего не шлём — как свёрнутая вкладка, где не тикает rAF.
  // Сокет при этом жив и отвечает на ping сам, средствами протокола.
  log('  молчим двадцать секунд, сокет отвечает на ping сам…');
  await wait(20000);
  log(`  итог: ${c.закрыт ? 'выкинули (' + c.закрыт + ')' : 'в мире'}, снимков за это время ${c.снимков}`);
  проверить('живой сокет не выкидывают за молчание', !c.закрыт,
    c.закрыт || 'остались в мире',
    'вкладка в фоне двадцать секунд — и игрок молча выпал из мира, хотя связь была цела');
  try { c.ws.close(); } catch { /* уже нет */ }
  await wait(300);
}

// ══════════════════════════════ обрыв замечен и назван

log('');
log('── обрыв замечен');
{
  const token = await гость();
  const m = await net.connect(`ws://localhost:${PORT}/`, { name: 'Оборванный', token });
  проверить('вошли, чтобы было что рвать', !!m, m ? 'welcome' : 'не вошли',
    'сцену собрать не удалось');
  if (m) {
    let сказали = null;
    net.onDrop = (почему) => { сказали = почему || 'без причины'; };
    // Рвём со стороны сокета — как рвётся сеть у игрока.
    try { net.ws.close(4000, 'проверка'); } catch { /* уже нет */ }
    await wait(800);
    log(`  состояние: ${net.state}; игре сказали: ${сказали === null ? 'НИЧЕГО' : сказали}`);
    проверить('игре сообщают об обрыве', сказали !== null,
      сказали === null ? 'обратного вызова нет' : сказали,
      'мир молча становится одиночным: соседи исчезли, бой идёт, и ничего из этого не попадёт в общий мир');
  }
  net.disconnect();
  net.onDrop = null;
}

console.log('');
console.log(`проверок: ${сделано}`);
if (problems.length) {
  console.log(`найдено: ${problems.length}`);
  for (const p of problems) console.log('  ' + p);
  process.exit(1);
}
console.log('ПРОБЛЕМ НЕ НАЙДЕНО');
process.exit(0);
