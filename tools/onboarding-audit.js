// Хронометраж входа: первые десять минут глазами человека, который здесь впервые.
//
//   node tools/onboarding-audit.js [минут]
//
// Этот замер уже делался однажды — и потерялся вместе со скриптом, который жил
// в черновиках. Проверка, которую нельзя повторить, проверкой не является: игра
// с тех пор обзавелась третьим актом, ручным выбором топлива, переделанным
// профилем оружия и управлением с касаний, и что из этого сдвинуло вход, никто
// сказать не мог. Поэтому теперь она здесь, рядом с остальными.
//
// Стенд поднимает **настоящую игру** без экрана: тот же `Game`, те же квесты,
// НПС, подсказки и указатель цели. Ничего не изображается — если бы стенд
// повторял правила своими словами, он мерил бы себя.
//
// Игровой цикл на время замера ведём вручную, фиксированным шагом. Иначе игра
// живёт между шагами бота сама: пока он «думает», герой стоит вплотную к твари
// и успевает умереть — мы бы мерили не вход, а задумчивость стенда.
//
// Бот намеренно простой: идёт к указателю цели, разговаривает, когда дошёл, и
// бьёт то, что мешает пройти. Он не отступает, не лечится с умом и не выбирает
// цели. Так и задумано — он мерит **дорогу**, а не мастерство: сколько времени
// человек идёт, ждёт и не понимает, куда деться. Числа про бой берёт combat-audit.

import { installHeadless } from '../src/core/headless.js';

installHeadless();

const { initProps } = await import('../src/art/props.js');
const { bakeAllMonsters } = await import('../src/art/sprites.js');
const { Game } = await import('../src/game.js');
const { objectiveOf } = await import('../src/systems/objective.js');
const { dist } = await import('../src/core/util.js');

initProps();
bakeAllMonsters();

const МИНУТ = Number(process.argv[2] || 10);
const DT = 1 / 30;
const ШАГОВ = Math.round((МИНУТ * 60) / DT);

const problems = [];
const note = (kind, what) => problems.push({ kind, what });
const fmt = (n, d = 1) => Number(n).toFixed(d).replace('.', ',');
const мин = (s) => `${(s / 60) | 0}:${String(Math.round(s % 60)).padStart(2, '0')}`;

// ─────────────────────────────────────────── игра без экрана

const VIEW = { w: 480, h: 270 };
const холст = (w, h) => { const c = document.createElement('canvas'); c.width = w; c.height = h; return c.getContext('2d'); };
const game = new Game(холст(480, 270), VIEW, холст(1920, 1080));
game.newGame();

// Ввод подделываем на том же объекте, который читает игра: бот нажимает те же
// действия, что и человек, а не дёргает методы напрямую.
const inp = game.input;
const держать = (a, да) => { if (да) inp.down.add(a); else inp.down.delete(a); };
const нажать = (a) => { inp.down.add(a); inp.justPressed.add(a); };

// ── меню проходим кнопками, а не в обход
//
// Области нажатия меню строятся **при отрисовке** — иначе их не существует.
// Поэтому стенд рисует каждый кадр (0,12 мс без экрана, дёшево) и жмёт те же
// кнопки, что человек. Это заодно и проверка: если интерфейс новичка где-то
// падает, прогон упадёт вместе с ним.
//
// Дорога к первому заданию оказалась длиннее, чем помнилось: поговорить с
// капитаном → «Задания» → журнал → «Принять». Бот идёт ровно ею.
const кнопки = () => (game.menus._clickables || []).filter((c) => c.action);

// Какая из кнопок нужная — стенд не знает и знать не должен: он не читает
// подписи и не помнит вёрстку. Он перебирает их по одной, кадр за кадром, пока
// не случится то, ради чего пришёл. Так проверка не ломается от перестановки
// вкладок и не притворяется, будто ей известно больше, чем игроку.
let перебор = 0;
const перебратьКнопки = () => {
  const к = кнопки();
  if (!к.length) return false;
  к[перебор++ % к.length].action();
  return true;
};

// ─────────────────────────────────────────── хроника

const хроника = [];
const было = new Set();
const событие = (t, что) => { if (было.has(что)) return; было.add(что); хроника.push({ t, что }); };

let t = 0;
let ходьба = 0, бой = 0, простой = 0;
let деньПоследнегоСобытия = 0;
let худшаяТишина = 0, тишинаКогда = 0;
let мёртвС = -1;
let былоX = 0, былоY = 0, залип = 0, обходДо = -1, обходЗнак = 1;
let путь = 0, прежнийX = 0, прежнийY = 0;
let безЦели = 0;
// Приговор — только по окну, за которое стенд ручается: первые полминуты
// разыграны почти по нотам. Дальше указатель гаснет там, куда забрёл бот, и
// это его беда, а не игры: замер по сорока прогонам дал одну и ту же долю до
// и после починки самого указателя — 10%. Постоянно краснеющая проверка хуже
// отсутствующей: к ней привыкают.
const ОКНО = 30;
let безЦелиВНачале = 0;
let когда0Подсказки = -1;
const p0 = game.player;
let смертей = 0;
const мёртвыеУчастки = [];

for (let шаг = 0; шаг < ШАГОВ; шаг++) {
  const p = game.player;

  // ── бот
  const цель = objectiveOf(game);
  const враг = game.enemies.find((e) => !e.dead && e.aggro && dist(e.x, e.y, p.x, p.y) < p.attackRange + 14);

  держать('left', false); держать('right', false); держать('up', false); держать('down', false);
  let идёт = false;
  if (враг) {
    p.facing = Math.atan2(враг.y - p.y, враг.x - p.x);
    нажать('attack');
  } else if (цель) {
    const d = dist(цель.x, цель.y, p.x, p.y);
    if (d > 26) {
      идёт = true;
      // ── обход препятствия
      //
      // Бот ходит по прямой на цель, и первый же прогон показал, чем это
      // кончается: с сороковой секунды герой стоял на одном месте и упирался в
      // камень, а стенд бодро считал это «ходьбой». Человек в такой ситуации
      // сдвигается вбок и обходит — иначе мы мерили бы не дорогу, а тупость
      // бота. Признак затыка простой: идём, а не двигаемся.
      // Замеряем сдвиг на окне в полсекунды, а не покадрово: за кадр герой
      // проходит около двух пикселей, и порог «меньше трёх» ловил бы обычную
      // ходьбу. Первая версия так и сделала — бот ушёл в вечный обход и не
      // вышел даже из города.
      залип++;
      if (залип >= 15) {
        const прошёл = dist(p.x, p.y, былоX, былоY);
        былоX = p.x; былоY = p.y; залип = 0;
        if (прошёл < 12 && обходДо < t) { обходДо = t + 1.2; обходЗнак = -обходЗнак; }
      }
      let dx = цель.x - p.x, dy = цель.y - p.y;
      if (обходДо > t) { const tx = dx; dx = -dy * обходЗнак; dy = tx * обходЗнак; }
      держать('right', dx > 4); держать('left', dx < -4);
      держать('down', dy > 4); держать('up', dy < -4);
    } else {
      нажать('interact');           // дошёл — заговорить или войти
    }
  }
  if (p.hp < p.maxHp * 0.4) нажать('potion');

  game.update(DT);
  game.draw();                      // без отрисовки у меню нет кнопок

  // ── в меню бот ведёт себя как человек, которому нужно задание
  if (game.menus.mode === 'dialogue') {
    // первый вариант — по делу, последний всегда «Уйти»
    const опции = кнопки();
    if (опции.length > 1) опции[0].action();
    else if (опции.length) опции[0].action();
  } else if (game.menus.mode === 'journal') {
    const естьДело = game.quests.available.length > 0 ||
                     game.quests.active.some((q) => game.quests.canComplete(q, p));
    if (естьДело) перебратьКнопки();
    else { game.menus.close(); перебор = 0; }
  } else if (game.menus.mode === 'death') {
    game.respawn();
  } else if (game.menus.mode) {
    game.menus.close();             // всё прочее новичку сейчас не нужно
  }

  // Экран смерти игра показывает через `setTimeout` на 1,1 с — это настоящие
  // часы, а не игровые. Цикл стенда синхронный, таймеры в нём не срабатывают
  // вовсе, и первый же прогон это поймал: бот умер на 51-й секунде и девять
  // минут «шёл», будучи мёртвым. Ждём столько же по игровому времени и
  // возрождаемся сами — человек нажал бы то же самое.
  if (p.dead) {
    мёртвС = мёртвС < 0 ? t : мёртвС;
    if (t - мёртвС > 1.2) { game.respawn(); мёртвС = -1; }
  } else мёртвС = -1;

  inp.endFrame();
  t += DT;

  if (враг) бой += DT; else if (идёт) ходьба += DT; else простой += DT;
  if (прежнийX) путь += Math.min(20, dist(p.x, p.y, прежнийX, прежнийY));
  прежнийX = p.x; прежнийY = p.y;

  // ── что заметил бы человек
  if (!цель) { безЦели += DT; if (t <= ОКНО) безЦелиВНачале += DT; }
  if (game.hud.lessons.length && когда0Подсказки < 0) когда0Подсказки = Math.round(t);
  if (game.hud.lessons.length) событие(t, 'первая подсказка: ' + (game.hud.lessons[0].title || game.hud.lessons[0].id || '—'));
  if ((p.kills || 0) >= 1) событие(t, 'первое убийство');
  if (p.level >= 2) событие(t, 'второй уровень');
  if (p.level >= 3) событие(t, 'третий уровень');
  if (game.quests.active.length) событие(t, 'первое задание взято');
  if (game.quests.completedIds.length) событие(t, 'первое задание сдано');
  if (p.inventory.length > 0) событие(t, 'первая вещь в рюкзаке');
  if (p.equipment.skill1) событие(t, 'первая руна умения вставлена');
  if (game.zone.kind === 'biome') событие(t, 'вышел из города в биом');
  if (p.dead && мёртвС === t) { смертей++; событие(t, 'первая смерть'); }

  // ── тишина: сколько человек идёт, ничего не получая
  const последнее = хроника.length ? хроника[хроника.length - 1].t : 0;
  if (последнее > деньПоследнегоСобытия) {
    const пауза = последнее - деньПоследнегоСобытия;
    if (пауза > 45) мёртвыеУчастки.push({ от: деньПоследнегоСобытия, до: последнее, длина: пауза });
    деньПоследнегоСобытия = последнее;
  }
  const тишина = t - деньПоследнегоСобытия;
  if (тишина > худшаяТишина) { худшаяТишина = тишина; тишинаКогда = t; }
}

// ─────────────────────────────────────────── отчёт

console.log(`\n── Хроника входа (${МИНУТ} мин игрового времени)\n`);
for (const e of хроника) console.log(`  ${мин(e.t).padStart(5)}  ${e.что}`);
if (!хроника.length) console.log('  ничего не случилось вовсе');

// Что стенд успел сделать.
//
// Без этих чисел отчёт нечитаем: «восемь минут до второго уровня» — это и про
// длинную дорогу, и про бота, который не умеет драться, а различить нельзя.
// Убийства и опыт отделяют одно от другого, и по ним же видно, когда числам
// после первой минуты верить не стоит.
const всего = ходьба + бой + простой;
const доля = (x) => `${fmt(x / всего * 100, 0)}%`;
console.log(`\n── Что бот успел\n`);
console.log(`  убийств      ${p0.kills || 0}`);
console.log(`  смертей      ${смертей}`);
console.log(`  опыта        ${Math.round(p0.xp || 0)} из ${Math.round(p0.xpNext || 0)} до уровня`);
console.log(`  уровень      ${p0.level}`);
console.log(`  пройдено     ${Math.round(путь)} px (${fmt(путь / всего, 0)} px/с)`);

console.log(`\n── На что ушло время\n`);
console.log(`  ходьба   ${fmt(ходьба, 0).padStart(4)} с  ${доля(ходьба)}`);
console.log(`  бой      ${fmt(бой, 0).padStart(4)} с  ${доля(бой)}`);
console.log(`  простой  ${fmt(простой, 0).padStart(4)} с  ${доля(простой)}`);

console.log(`\n── Тишина: промежутки без единого события\n`);
if (мёртвыеУчастки.length) {
  for (const g2 of мёртвыеУчастки) console.log(`  ${мин(g2.от)} → ${мин(g2.до)}   ${fmt(g2.длина, 0)} с ничего`);
} else console.log('  длиннее 45 с не нашлось');
console.log(`  самая долгая тишина: ${fmt(худшаяТишина, 0)} с (к ${мин(тишинаКогда)})`);

// ─────────────────────────────────────────── чего этот стенд не мерит
//
// Бот ходит по прямой на цель и обходит препятствия вслепую: поиска пути в игре
// нет — его нет и у врагов, — и писать его ради замера значит проверять не игру.
// Цена видна в отчёте: средняя скорость выходит около 22 px/с при 62 у героя,
// то есть две трети «ходьбы» уходит на обходы.
//
// Отсюда правило: **судим только то, что от навигации не зависит.** Это первые
// полминуты — они разыграны почти по нотам, дорога от старта до капитана и в лес
// короткая и прямая, и повторяется от прогона к прогону. Всё, что дальше —
// сколько ходьбы, когда второй уровень, длина тишины — печатаем как наблюдение
// и в приговор не берём: там мерялся бот.
//
// Тишину и долю ходьбы всё равно показываем: если однажды они изменятся резко
// при тех же убийствах и той же скорости, это будет поводом посмотреть.

const когда = (что) => { const e = хроника.find((x) => x.что === что); return e ? e.t : Infinity; };
const былоЛи = (что) => хроника.some((x) => x.что.startsWith(что));

console.log(`\n── Приговор выносим только по началу — дальше мерялся бот\n`);
console.log(`  скорость бота ${fmt(путь / всего, 0)} px/с против 62 у героя — остальное съели обходы`);

const первоеЗадание = когда('первое задание взято');
const вБиом = когда('вышел из города в биом');
const первоеУбийство = когда('первое убийство');

if (первоеЗадание > 60) note('долго до первого задания', `${fmt(первоеЗадание, 0)} с`);
// Дорога до ворот — единственное в начале, что зависит от навигации, и бот
// иногда до них просто не доходит. `Infinity` — это про бота, а не про игру:
// сказать «долго до биома: бесконечность» значило бы записать в дефекты свою
// же слепоту. Не дошёл — говорим об этом прямо и в приговор не берём.
if (!Number.isFinite(вБиом)) console.log(`  бот не дошёл до биома за ${fmt(всего, 0)} с — эту часть не мерили`);
else if (вБиом > 90) note('долго до биома', `${fmt(вБиом, 0)} с`);
// «Долго до первого боя» — единственная из проверок начала, которая всё-таки
// зависит от навигации: до твари надо дойти. Один прогон из четырёх бот
// проводил, никого не встретив, и правило сваливало это на игру. Поэтому
// сначала спрашиваем, работал ли сам бот: дошёл ли до биома и не рухнула ли
// скорость. Если нет — это отчёт о стенде, а не находка.
const скорость = путь / всего;
// Защита была, но `Infinity > 60` — правда, и она проходила насквозь: два
// прогона из тридцати бот доходил до биома, шёл с нормальной скоростью и всё
// равно никого не убивал (застревал на щитоносце, кружил вокруг). Это отчёт о
// боте. Замер по тридцати прогонам: настоящее первое убийство — 21–30 с,
// однажды 39; шестьдесят как порог с большим запасом.
if (!Number.isFinite(первоеУбийство)) {
  console.log(`  ⚠ бот ни разу не подрался за ${fmt(всего, 0)} с — про темп боя этот прогон ничего не говорит`);
} else if (первоеУбийство > 60) {
  if (вБиом < Infinity && скорость > 18) note('долго до первого боя', `первое убийство на ${fmt(первоеУбийство, 0)} с`);
  else console.log(`  ⚠ бот не подрался толком (скорость ${fmt(скорость, 0)} px/с) — про бой этот прогон ничего не говорит`);
}
if (!былоЛи('первая подсказка')) note('ни одной подсказки', 'новичка никто ничему не научил');
// Ноль секунд — плохо не всегда. Правило писалось против карточки про руны,
// которая объясняла слоты умений человеку, ещё не сделавшему шага. Но карточка
// «как ходить» обязана быть первой: до неё игроку нечего узнавать. Судим по
// тому, чему учит, а не по секунде.
const перваяКарточка = хроника.find((x) => x.что.startsWith('первая подсказка'));
if (когда0Подсказки === 0 && перваяКарточка && !/Как играть|How to play/.test(перваяКарточка.что)) {
  note('подсказка на нулевой секунде', `«${перваяКарточка.что.replace('первая подсказка: ', '')}» — учит того, кто ещё не сделал шага`);
}
if (!перваяКарточка || !/Как играть|How to play/.test(перваяКарточка.что)) {
  note('не сказано, как играть', 'первая карточка — не про управление');
}

// ── указатель цели: проверка без бота
//
// Ниже есть та же проверка по ходу прогона, но она зависит от того, куда
// забрёл бот, и краснела примерно раз в десять прогонов — на таком стороже
// дыру не разглядишь. Эта не зависит ни от чего: по каждому заданию, стоя в
// городе, указатель обязан назвать место. Так и нашлись девять заданий из
// тридцати четырёх, на которых он просто гас: «собери» и «убей элиту» своего
// места не называют, и правило их не знало.
{
  const { objectiveOf } = await import('../src/systems/objective.js');
  const { QUEST_LINE } = await import('../src/systems/quests.js');
  const город = game.getCity();
  let слепых = 0;
  for (const q of QUEST_LINE) {
    const герой = Object.create(Object.getPrototypeOf(game.player));
    Object.assign(герой, game.player, { x: город.spawnPoint.x, y: город.spawnPoint.y, level: Math.max(1, q.minLevel || 1) });
    const цель = objectiveOf({
      zone: город, player: герой, enemies: [],
      quests: { active: [q], available: [], completedIds: [], canComplete: () => false },
    });
    if (!цель) { слепых++; note('задание без указателя', `${q.id} «${q.title}» (${q.type} → ${q.target})`); }
  }
  console.log('');
  console.log(`  указатель ведёт из города по ${QUEST_LINE.length - слепых} заданиям из ${QUEST_LINE.length}`);
}

// Подсказки, наступающие друг другу на пятки, не учат: карточку не дочитывают,
// её сменяет следующая. Считаем самый тесный промежуток между ними.
const подсказки = хроника.filter((x) => x.что.startsWith('первая подсказка')).map((x) => x.t);
let теснее = Infinity;
for (let i = 1; i < подсказки.length; i++) теснее = Math.min(теснее, подсказки[i] - подсказки[i - 1]);
if (подсказки.length > 1) console.log(`  подсказок ${подсказки.length}, теснее всего — ${fmt(теснее, 0)} с между ними`);
if (теснее < 12) note('подсказки наступают друг на друга', `${fmt(теснее, 0)} с между карточками — первую не дочитать`);

// Указатель цели — единственное, что ведёт новичка. Если он хоть раз пропал,
// человек остался без подсказки, куда идти.
if (безЦелиВНачале > 3) note('цель пропадала на входе', `${fmt(безЦелиВНачале, 0)} с из первых ${ОКНО} новичок не знал, куда идти`);
if (безЦели > 3) console.log(`  за весь прогон без указателя ${fmt(безЦели, 0)} с (наблюдение: дальше ходил бот)`);

console.log('');
if (!problems.length) { console.log('ПРОБЛЕМ НЕ НАЙДЕНО'); process.exit(0); }
console.log(`найдено: ${problems.length}`);
for (const p2 of problems) console.log(`  ${p2.kind}: ${p2.what}`);
process.exit(1);
